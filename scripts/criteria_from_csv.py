"""Build config/criteria_columns.yaml and config/criteria.yaml from CSSNY's Excel data dictionary.

    uv run python scripts/criteria_from_csv.py [--src CSV] [--overrides YAML] [--columns YAML] [--dst YAML]

Inputs
    config/criteria_raw.csv        The data dictionary: col 1 = section label (carries down), 2 = Excel
                                   letter, 3 = title, 4 = explanation ("question? / YES = ... / NO = ...").
    config/criteria_overrides.yaml The few things the CSV cannot say: section -> doc_types, expected
                                   count, and per-column question / guidance / yes_means / no_means overrides
                                   (an override replaces that part of the CSV's text; "" removes it).
                                   Also `checks` and `notes` (lists, new in the rubric) and a top-level
                                   `reading_rules` text for the system prompt.

Outputs (same inputs always give the same files)
    config/criteria_columns.yaml   Inventory of every CSV row: criterion or not, and why.
    config/criteria.yaml           The criteria the pipeline uses.

Rules
    - A row is a criterion if its explanation has both a "YES =" and a "NO =" line, or if it has an
      override that supplies yes_means and no_means.
    - id = the title with parentheses removed, lowercased, snake_case.
    - question = the CSV's first line if it ends in "?", else the override, else the title + "?".
    - guidance = other text before "YES =". Text after a blank line following the NO block is dropped.
    - doc_types come from the section label.
Nothing is written unless every criterion parses.
"""

import argparse
import re
import sys
from pathlib import Path

import yaml

from hfal import paths
from hfal.files import read_csv_rows, write_atomic
from hfal.tag import RULES

GENERATED = "# GENERATED by scripts/criteria_from_csv.py. Edit criteria_raw.csv / criteria_overrides.yaml, not this file.\n"
FIELD_ORDER = ["id", "section", "short_name", "question", "guidance", "checks", "yes_means", "no_means", "notes", "doc_types"]
NBSP = " "


def squash(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace(NBSP, " ")).strip()


def key(text: str) -> str:
    """Comparable form of a title: lowercase, straight quotes, single spaces."""
    t = squash(text).lower()
    return t.replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"')


def slug(title: str) -> str:
    t = re.sub(r"\([^)]*\)", " ", title).replace("&", " and ")
    return re.sub(r"[^a-z0-9]+", "_", t.lower()).strip("_")


def parse_explanation(text: str) -> dict:
    """Split one explanation cell. Returns question, guidance, yes_means, no_means, dropped, errors."""
    lines = [ln.replace(NBSP, " ").strip() for ln in text.splitlines()]
    out = {"question": "", "guidance": "", "yes_means": "", "no_means": "", "dropped": False, "errors": []}

    yes_i = next((i for i, ln in enumerate(lines) if re.match(r"YES\s*=", ln)), None)
    no_i = None if yes_i is None else next(
        (i for i, ln in enumerate(lines) if i > yes_i and re.match(r"NO\s*=", ln)), None
    )
    if yes_i is None or no_i is None:  # not a YES/NO row: everything is background text
        out["guidance"] = squash(" ".join(re.sub(r"^-\s*", "", ln) for ln in lines))
        out["errors"].append("no 'YES =' and 'NO =' lines")
        return out

    pre = [ln for ln in lines[:yes_i] if ln]
    if pre and pre[0].endswith("?"):
        out["question"], pre = pre[0], pre[1:]
    out["guidance"] = squash(" ".join(re.sub(r"^-\s*", "", ln) for ln in pre))
    out["yes_means"] = squash(re.sub(r"^YES\s*=\s*", "", " ".join(lines[yes_i:no_i])))

    tail = lines[no_i:]
    blank = next((i for i, ln in enumerate(tail) if not ln), None)
    if blank is not None:
        out["dropped"] = any(tail[blank:])
        tail = tail[:blank]
    out["no_means"] = squash(re.sub(r"^NO\s*=\s*", "", " ".join(tail)))
    return out


def read_rows(rows: list[list[str]]) -> list[dict]:
    """One dict per CSV row that has an Excel letter. Section labels carry down."""
    out, current = [], ""
    for r in rows:
        if r and r[0].strip():
            current = squash(r[0]).upper()
        if len(r) > 3 and r[1].strip():
            out.append({"col": r[1].strip(), "title": squash(r[2]), "section": current, "text": r[3]})
    return out


def build(rows: list[list[str]], conf: dict) -> tuple[list[dict], list[dict], list[str], list[str]]:
    """Returns (criteria, inventory, errors, notes)."""
    errors, notes = [], []
    sections = {squash(k).upper(): v for k, v in conf["sections"].items()}
    overrides = {str(k): v for k, v in (conf.get("overrides") or {}).items()}
    items = read_rows(rows)

    letters = [i["col"] for i in items]
    for dup in sorted({c for c in letters if letters.count(c) > 1}):
        errors.append(f"column {dup} appears more than once in the CSV")
    for col, ov in overrides.items():
        match = next((i for i in items if i["col"] == col), None)
        if match is None:
            errors.append(f"override {col}: column not found in the CSV")
        elif not key(match["title"]).startswith(key(ov["title"])):
            errors.append(f"override {col}: CSV title is {match['title']!r}, expected it to start with {ov['title']!r}")

    criteria, inventory, ids = [], [], {}
    for item in items:
        col, title = item["col"], item["title"]
        ov = overrides.get(col, {})
        parsed = parse_explanation(item["text"])
        has_yes_no = not parsed["errors"]
        if not has_yes_no and ov.get("yes_means") and ov.get("no_means"):
            parsed.update(errors=[], yes_means=squash(ov["yes_means"]), no_means=squash(ov["no_means"]))
        elif not has_yes_no:
            inventory.append({"col": col, "title": title, "section": item["section"].title(),
                              "criterion": False, "reason": "no YES/NO lines in the CSV and no override"})
            continue

        tag = f"{col} ({title})"
        cid = slug(title)
        if cid in ids:
            errors.append(f"{tag}: id {cid!r} repeats column {ids[cid]}")
        ids[cid] = col
        doc_types = sections.get(item["section"])
        if doc_types is None:
            errors.append(f"{tag}: CSV section {item['section']!r} has no entry under `sections` in criteria_overrides.yaml")
            continue
        bad = [t for t in doc_types if t not in RULES]
        if bad:
            errors.append(f"{tag}: unknown doc_types {bad}")
        reworded = [f for f in ("guidance", "yes_means", "no_means") if f in ov and (has_yes_no or f == "guidance")]
        for f in reworded:              # our own wording replaces the CSV's text; the CSV itself is never changed
            parsed[f] = squash(ov[f])   # an empty string removes that part
        if reworded:
            notes.append(f"{tag}: reworded by criteria_overrides.yaml: {', '.join(reworded)}")
        question = squash(ov.get("question", "")) or parsed["question"] or (re.sub(r"\([^)]*\)", "", title).strip().rstrip("?").strip() + "?")
        if parsed["dropped"]:
            notes.append(f"{tag}: ignored text after the blank line following the NO block")

        entry = {"id": cid, "section": item["section"].title(), "short_name": title, "question": question,
                 "guidance": parsed["guidance"], "yes_means": parsed["yes_means"], "no_means": parsed["no_means"],
                 "checks": [squash(x) for x in ov.get("checks", [])], "notes": [squash(x) for x in ov.get("notes", [])],
                 "doc_types": list(doc_types)}
        criteria.append({k: entry[k] for k in FIELD_ORDER if entry[k]})
        inventory.append({"col": col, "title": title, "section": item["section"].title(),
                          "criterion": True, "id": cid})
    notes.append("not criteria: " + "; ".join(f"{i['col']} {i['title']}" for i in inventory if not i["criterion"]))
    return criteria, inventory, errors, notes


def squash_lines(text: str) -> str:
    """Tidy trailing spaces and extra blank lines but keep the line breaks (the reading rules are a list)."""
    return re.sub(r"\n{3,}", "\n\n", "\n".join(ln.rstrip() for ln in text.strip().splitlines()))


def dump(data) -> str:
    return GENERATED + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100, default_flow_style=None)


def consistency_points(conf: dict) -> tuple[list[dict], list[str]]:
    """`consistency_points` from the overrides file (prompt v7 on), checked: each {id, text, counts}. The ids
    become the enum of the model's reply, so they must be unique slugs."""
    points, errors, seen = [], [], set()
    for i, p in enumerate(conf.get("consistency_points") or []):
        pid, text, counts = str(p.get("id", "")).strip(), str(p.get("text", "")).strip(), p.get("counts", True)
        if not re.fullmatch(r"[a-z][a-z0-9_]*", pid):
            errors.append(f"consistency_points[{i}]: id {pid!r} must be a lowercase slug")
        elif pid in seen:
            errors.append(f"consistency_points[{i}]: duplicate id {pid!r}")
        if not text:
            errors.append(f"consistency_points[{i}] ({pid}): text is empty")
        if not isinstance(counts, bool):
            errors.append(f"consistency_points[{i}] ({pid}): counts must be true or false")
        seen.add(pid)
        points.append({"id": pid, "text": " ".join(text.split()), "counts": counts})
    return points, errors


def _not_written(*problems: str) -> int:
    print("NOT WRITTEN:", *[f"  - {e}" for e in problems], sep="\n", file=sys.stderr)
    return 1


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--src", type=Path, default=paths.CONFIG / "criteria_raw.csv")
    p.add_argument("--overrides", type=Path, default=paths.CONFIG / "criteria_overrides.yaml")
    p.add_argument("--columns", type=Path, default=paths.CONFIG / "criteria_columns.yaml")
    p.add_argument("--dst", type=Path, default=paths.CONFIG / "criteria.yaml")
    args = p.parse_args()

    rows = read_csv_rows(args.src)
    conf = yaml.safe_load(args.overrides.read_text(encoding="utf-8"))

    criteria, inventory, errors, notes = build(rows, conf)
    for n in notes:
        print(f"note: {n}")
    if errors:
        return _not_written(*errors)

    write_atomic(args.columns, dump({"columns": inventory}))
    rules = squash_lines(conf.get("reading_rules") or "")
    refs = {k: conf[k] for k in ("reference_form", "reference_fpl") if conf.get(k)}
    for k, ref in refs.items():
        if not (paths.CONFIG / ref).exists():
            print(f"NOT WRITTEN: {k} {ref} does not exist (reference_form: run scripts/build_reference_form.py)", file=sys.stderr)
            return 1
    points, point_errors = consistency_points(conf)
    if point_errors:
        return _not_written(*point_errors)
    write_atomic(args.dst, dump({**({"reading_rules": rules} if rules else {}), **refs,
                                 **({"consistency_points": points} if points else {}), "criteria": criteria}))
    print(f"wrote {len(criteria)} criteria -> {args.dst}\nwrote {len(inventory)}-row inventory -> {args.columns}")

    rubric_file = paths.CONFIG / "rubric.yaml"
    if rubric_file.exists():
        auto = yaml.safe_load(rubric_file.read_text(encoding="utf-8")).get("automatic_fail") or []
        absent = [c for c in auto if c not in {x["id"] for x in criteria}]
        if absent:
            print(f"WARNING: rubric automatic_fail ids not in the criteria: {absent}")
    expected = conf.get("expected_count")
    if expected and len(criteria) != expected:
        print(f"WARNING: {len(criteria)} criteria, criteria_overrides.yaml expects {expected}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
