"""Convert CSSNY's golden sheet into long-format labels and their published grades.

    uv run python scripts/golden_convert.py [--src CSV] [--columns YAML] [--out-dir DIR]

Inputs
    golden/golden_raw.csv          Two header rows (row 1 = section labels, row 2 = column names).
    config/criteria_columns.yaml   Generated by criteria_from_csv.py: Excel column letter -> criterion id.

Outputs (same inputs always give the same files)
    golden/golden.csv              hospital_id, criterion_id, label   (YES / NO / N/A)
    golden/golden_grades.csv       hospital_id, letter, auto_fail, noncompliant_count   (CSSNY's own values)

Columns are matched by Excel letter (the golden sheet and the data dictionary share the layout) and
each title is checked for similarity, so a shifted column fails loudly instead of mislabeling.

Label rules
    yes / y / true -> YES,  no / n / false -> NO,  n/a / na -> N/A.  Blank -> skipped and counted.
    Anything else -> skipped and counted as unrecognized (never guessed).
    max_fpl              "no" -> NO; otherwise the largest "NNN%" in the cell: >= 400 -> YES, < 400 -> NO.
    languages_available  YES if the cell names any language besides English, NO if English only.
                         (CSSNY's sheet lists languages, not YES/NO; this rule matches our criterion text.)

Prints counts only. Never prints hospital names, ids or labels.
"""

import argparse
import difflib
import re
import sys
from collections import Counter
from pathlib import Path

import yaml

from hfal import paths
from hfal.files import read_csv_rows, write_csv
from hfal.schema import NA, NO, YES, hospital_id

ID_COL = "Permanent Facility Identifier (PFI)"
OUTCOME_COLS = {"letter": "COMPLIANCE GRADE", "auto_fail": "Automatic Fail?", "noncompliant_count": "Noncompliant Categories Count"}
TITLE_MIN_SIMILARITY = 0.75
GENERIC = {"yes": YES, "y": YES, "true": YES, "no": NO, "n": NO, "false": NO, "n/a": NA, "na": NA}
NOT_LANGUAGES = {"english", "and", "only", "the", "in", "available", "also"}
LABEL_FIELDS = ["hospital_id", "criterion_id", "label"]
GRADE_FIELDS = ["hospital_id", "letter", "auto_fail", "noncompliant_count"]


def col_index(letter: str) -> int:
    """Excel column letter -> 0-based index ("A" -> 0, "AB" -> 27)."""
    n = 0
    for ch in letter.upper():
        n = n * 26 + ord(ch) - 64
    return n - 1


def norm_title(t: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", t.lower()).strip()


def to_label(criterion_id: str, raw: str) -> str | None:
    """Returns YES / NO / N/A, "" for blank, or None for an unrecognized value."""
    v = raw.strip().lower()
    if not v:
        return ""
    if criterion_id == "max_fpl":
        if v in GENERIC:
            return GENERIC[v]
        pct = [int(x) for x in re.findall(r"(\d+)\s*%", v)]
        return (YES if max(pct) >= 400 else NO) if pct else None
    if criterion_id == "languages_available":
        if v in ("n/a", "na"):
            return NA
        words = set(re.findall(r"[a-z]+", v))
        if not words:
            return None
        return YES if words - NOT_LANGUAGES else NO
    return GENERIC.get(v)


def to_bool(raw: str) -> str:
    v = raw.strip().lower()
    return {"true": "TRUE", "yes": "TRUE", "false": "FALSE", "no": "FALSE"}.get(v, "")


def _criterion_columns(names: list[str], columns: list[dict], errors: list[str]) -> list[tuple[str, int]]:
    """(criterion id, column index) for every criterion column whose golden title matches the data dictionary's."""
    crit = []
    for c in (c for c in columns if c["criterion"]):
        i = col_index(c["col"])
        if i >= len(names):
            errors.append(f"{c['col']} ({c['id']}): golden sheet has no column {c['col']}")
            continue
        sim = difflib.SequenceMatcher(None, norm_title(names[i]), norm_title(c["title"])).ratio()
        if sim < TITLE_MIN_SIMILARITY:
            errors.append(f"{c['col']} ({c['id']}): golden title {names[i]!r} does not match {c['title']!r} (similarity {sim:.2f})")
            continue
        crit.append((c["id"], i))
    return crit


def convert(rows: list[list[str]], columns: list[dict]) -> tuple[list[dict], list[dict], Counter, list[str]]:
    """Returns (labels, grades, stats, errors)."""
    errors, stats = [], Counter()
    if len(rows) < 3:
        return [], [], stats, ["expected two header rows and data"]
    names = [n.strip() for n in rows[1]]

    def find(name):
        if name not in names:
            errors.append(f"column {name!r} not found in header row 2")
            return None
        return names.index(name)

    i_id = find(ID_COL)
    i_out = {k: find(v) for k, v in OUTCOME_COLS.items()}
    crit = _criterion_columns(names, columns, errors)
    if errors:
        return [], [], stats, errors

    labels, grades, seen = [], [], Counter()
    for r in rows[2:]:
        if not any(x.strip() for x in r):
            continue

        def cell(i, r=r):
            return r[i] if i is not None and i < len(r) else ""

        stats["rows"] += 1
        hid = hospital_id(cell(i_id))
        if not hid:
            stats["rows_without_pfi"] += 1
            continue
        seen[hid] += 1
        if seen[hid] > 1:
            stats["duplicate_pfi_rows_skipped"] += 1
            continue
        for cid, i in crit:
            lab = to_label(cid, cell(i))
            if lab == "":
                stats[f"blank:{cid}"] += 1
            elif lab is None:
                stats[f"unrecognized:{cid}"] += 1
            else:
                stats[f"{lab}"] += 1
                labels.append({"hospital_id": hid, "criterion_id": cid, "label": lab})
        count = cell(i_out["noncompliant_count"]).strip()
        grades.append({
            "hospital_id": hid,
            "letter": cell(i_out["letter"]).strip().upper(),
            "auto_fail": to_bool(cell(i_out["auto_fail"])),
            "noncompliant_count": count if count.isdigit() else "",
        })
        for k in GRADE_FIELDS[1:]:
            if not grades[-1][k]:
                stats[f"missing_or_unrecognized:{k}"] += 1
    stats["hospitals"] = len(grades)
    order = {cid: n for n, (cid, _) in enumerate(crit)}
    labels.sort(key=lambda x: (x["hospital_id"], order[x["criterion_id"]]))
    grades.sort(key=lambda x: x["hospital_id"])
    return labels, grades, stats, errors


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--src", type=Path, default=paths.GOLDEN / "golden_raw.csv")
    p.add_argument("--columns", type=Path, default=paths.CONFIG / "criteria_columns.yaml")
    p.add_argument("--out-dir", type=Path, default=paths.GOLDEN)
    args = p.parse_args()

    rows = read_csv_rows(args.src)
    columns = yaml.safe_load(args.columns.read_text(encoding="utf-8"))["columns"]
    labels, grades, stats, errors = convert(rows, columns)
    if errors:
        print("NOT WRITTEN:", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        return 1

    write_csv(args.out_dir / "golden.csv", labels, LABEL_FIELDS, atomic=True)
    write_csv(args.out_dir / "golden_grades.csv", grades, GRADE_FIELDS, atomic=True)
    for k, v in sorted(stats.items()):
        print(f"{k}: {v}")
    print(f"wrote {len(labels)} labels -> {args.out_dir / 'golden.csv'}")
    print(f"wrote {len(grades)} grades -> {args.out_dir / 'golden_grades.csv'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
